'use strict';

// Cache name — bump the version suffix when assets change to force re-cache.
const CACHE_NAME = 'avalanche-v2';

// Base path for the site.  On GitHub Pages the game lives under a sub-path
// (e.g. /repo/) rather than at the domain root, so absolute paths like
// '/index.html' would resolve to the wrong location.  Computing BASE from
// self.location ensures the pre-cache URLs are correct both on localhost
// (BASE = '/') and on GitHub Pages (BASE = '/repo/').
const BASE = new URL('./', self.location.href).pathname;

// Shell assets that are pre-cached on SW install so the game loads offline
// after the first visit.  All paths are relative to BASE (same-origin).
// NOTE: favicon.png is intentionally excluded — it is generated by pygbag at
// build time and may not exist on a fresh checkout.  The _cacheFirst handler
// caches it lazily on the first request instead.
const SHELL_URLS = [
    BASE + 'index.html',
    BASE + 'manifest.json',
    BASE + 'icon-192.png',
    BASE + 'icon-512.png',
];

// ---- Install: pre-cache shell -----------------------------------------------
self.addEventListener('install', (evt) => {
    evt.waitUntil(
        caches.open(CACHE_NAME)
            .then((cache) => cache.addAll(SHELL_URLS))
            .then(() => self.skipWaiting())   // activate immediately
    );
});

// ---- Activate: clean stale caches + claim clients ---------------------------
self.addEventListener('activate', (evt) => {
    evt.waitUntil(
        caches.keys()
            .then((keys) => Promise.all(
                keys
                    .filter((k) => k !== CACHE_NAME)
                    .map((k) => caches.delete(k))
            ))
            .then(() => self.clients.claim())
    );
});

// ---- Fetch: route by resource type ------------------------------------------
self.addEventListener('fetch', (evt) => {
    // Only intercept GET requests.
    if (evt.request.method !== 'GET') return;

    // Only intercept same-origin requests.  Cross-origin CDN assets (pythons.js,
    // WASM, browserfs) are opaque responses that browsers pad to ~7 MB in Cache
    // Storage quota regardless of actual size.  Routing them through the SW
    // risks QuotaExceededError on mobile and locks the CDN version indefinitely.
    const reqUrl = new URL(evt.request.url);
    if (reqUrl.origin !== self.location.origin) return;

    const { pathname } = reqUrl;

    // Large binary assets (.wasm, .data) and the packed game archive:
    // serve stale copy immediately while refreshing in the background.
    const isBigBinary = (
        pathname.endsWith('.wasm') ||
        pathname.endsWith('.data') ||
        pathname.endsWith('.tar.gz') ||
        pathname.endsWith('.apk')
    );

    if (isBigBinary) {
        evt.respondWith(_staleWhileRevalidate(evt.request));
    } else {
        // Everything else (HTML, JS, icons, manifest): cache-first.
        evt.respondWith(_cacheFirst(evt.request));
    }
});

// ---- Strategies -------------------------------------------------------------

/**
 * Stale-while-revalidate: return the cached response immediately (if any)
 * and refresh the cache entry in the background.
 */
function _staleWhileRevalidate(req) {
    return caches.open(CACHE_NAME).then((cache) =>
        cache.match(req).then((cached) => {
            const fresh = fetch(req).then((resp) => {
                // Cache successful same-origin responses and opaque cross-origin
                // responses (CDN assets that don't need CORS inspection).
                if (resp.ok || resp.type === 'opaque') {
                    cache.put(req, resp.clone());
                }
                return resp;
            }).catch(() => null);   // network unavailable — fresh is null
            return cached || fresh; // serve cached first, fall through to fresh
        })
    );
}

/**
 * Cache-first: serve from cache if available; fetch and cache on miss.
 * Returns a 503 offline placeholder only if both cache and network fail.
 */
function _cacheFirst(req) {
    return caches.open(CACHE_NAME).then((cache) =>
        cache.match(req).then((cached) => {
            if (cached) return cached;
            return fetch(req).then((resp) => {
                if (resp.ok || resp.type === 'opaque') {
                    cache.put(req, resp.clone());
                }
                return resp;
            }).catch(() =>
                new Response('Offline', {
                    status: 503,
                    statusText: 'Service Unavailable',
                })
            );
        })
    );
}
